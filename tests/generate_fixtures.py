"""
Helper script to generate explicitly labeled synthetic PDF test fixtures.

NOTE: All PDFs generated by this script are explicitly labeled as synthetic software test fixtures
and are strictly NOT authentic StEER reconnaissance documents.
"""

from pathlib import Path


def create_minimal_pdf(text_lines: list[str], output_path: Path) -> None:
    """Generate a valid single-page PDF with text stream using standard PDF 1.4 syntax."""
    escaped_ops = []
    for line in text_lines:
        clean = line.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
        escaped_ops.append(f"({clean}) Tj T*")
    text_block = " ".join(escaped_ops)

    content_stream = f"BT /F1 11 Tf 50 720 Td 15 TL {text_block} ET".encode("latin1")
    stream_len = len(content_stream)

    pdf_bytes = f"""%PDF-1.4
1 0 obj
<< /Type /Catalog /Pages 2 0 R >>
endobj
2 0 obj
<< /Type /Pages /Kids [3 0 R] /Count 1 >>
endobj
3 0 obj
<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>
endobj
4 0 obj
<< /Length {stream_len} >>
stream
{content_stream.decode('latin1')}
endstream
endobj
5 0 obj
<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>
endobj
xref
0 6
0000000000 65535 f 
0000000009 00000 n 
0000000058 00000 n 
0000000115 00000 n 
0000000224 00000 n 
0000000300 00000 n 
trailer
<< /Size 6 /Root 1 0 R >>
startxref
400
%%EOF
""".encode("latin1")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "wb") as f:
        f.write(pdf_bytes)


def create_blank_scanned_pdf(output_path: Path) -> None:
    """Generate a valid single-page PDF without any text layer (simulates scanned image)."""
    pdf_bytes = b"""%PDF-1.4
1 0 obj
<< /Type /Catalog /Pages 2 0 R >>
endobj
2 0 obj
<< /Type /Pages /Kids [3 0 R] /Count 1 >>
endobj
3 0 obj
<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] >>
endobj
xref
0 4
0000000000 65535 f 
0000000009 00000 n 
0000000058 00000 n 
0000000115 00000 n 
trailer
<< /Size 4 /Root 1 0 R >>
startxref
200
%%EOF
"""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "wb") as f:
        f.write(pdf_bytes)


